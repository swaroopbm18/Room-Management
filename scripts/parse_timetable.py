#!/usr/bin/env python3
"""Turn the department's Room Allocation Time Table (.docx) into supabase/seed.sql.

Usage:
    pip install python-docx
    python3 scripts/parse_timetable.py "Room Timetable.docx" > supabase/seed.sql

For a revised timetable, give it the next version number and the date it takes effect
(today or later; past days keep the old timetable):
    python3 scripts/parse_timetable.py "Revised.docx" --version 2 --from 2026-11-02 > revision.sql

The document holds, for every room, a one-row table with the room name followed by an
8-row grid: two header rows (times), then MON..SAT. Break columns are skipped.
"""
import argparse
import re
import sys

import docx

DAYS = {"MON": 1, "TUE": 2, "WED": 3, "THU": 4, "THUR": 4, "FRI": 5, "SAT": 6}
DEPARTMENTS = {"CSE", "MBA", "ISE", "ECE", "EEE", "MECH", "CIVIL"}
FACULTY_RE = re.compile(r"\b(Prof|Dr|Mr|Ms|Mrs)[.,]\s*([A-Z]{2,5})\b")
TIME_RE = re.compile(r"(\d{1,2}):(\d{2})\s*([AP]M)", re.I)

# Slots after the last column of the timetable (college day runs until 5:40 PM).
EXTRA_SLOTS = [("16:45", "17:40")]

# Defaults for the first import. Later revisions must start today or later.
VALID_FROM = "2026-10-08"
VALID_TO = "2026-12-31"


def q(s):
    return "'" + s.replace("'", "''") + "'"


def to_24h(h, m, ampm):
    h = int(h) % 12 + (12 if ampm.upper() == "PM" else 0)
    return f"{h:02d}:{m}"


def label(start, end):
    def fmt(t):
        h, m = map(int, t.split(":"))
        return f"{(h - 1) % 12 + 1}:{m:02d} {'AM' if h < 12 else 'PM'}"
    return f"{fmt(start)} – {fmt(end)}"


def main(path, version, valid_from, valid_to):
    doc = docx.Document(path)
    revised = ""
    rooms, slots, entries = [], None, []
    for para in doc.paragraphs:
        m = re.search(r"Revised On\s*([\d/]+)", para.text)
        if m:
            revised = m.group(1)
            break
    current_room = None
    for t in doc.tables:
        if len(t.rows) == 1:
            m = re.search(r"Room Name:\s*(.+)", t.rows[0].cells[0].text)
            if m:
                current_room = re.sub(r"\s+", "", m.group(1).strip())
                rooms.append(current_room)
            continue
        header = [c.text.strip() for c in t.rows[0].cells]
        cols = []  # (column index, start, end)
        for i, h in enumerate(header[1:], start=1):
            if "BREAK" in h.upper():
                continue
            times = TIME_RE.findall(h)
            if len(times) == 2:
                cols.append((i, to_24h(*times[0]), to_24h(*times[1])))
        if slots is None:
            slots = [(s, e) for _, s, e in cols] + EXTRA_SLOTS
        slot_id = {(s, e): n + 1 for n, (s, e) in enumerate(slots)}
        for row in t.rows[2:]:
            cells = row.cells
            day = DAYS.get(cells[0].text.strip().upper())
            if not day:
                continue
            for i, s, e in cols:
                text = cells[i].text.strip()
                if not text or "BREAK" in text.upper():
                    continue
                lines = [ln.strip() for ln in text.split("\n") if ln.strip()]
                subject = lines[0]
                fac_text = " ".join(lines[1:])
                # "DST-3E/Prof, BHL" style: faculty written on the same line
                if not fac_text and "/" in subject and FACULTY_RE.search(subject):
                    subject, fac_text = subject.split("/", 1)
                faculty = FACULTY_RE.findall(fac_text)
                initials = [ini for _, ini in faculty]
                fac_label = ", ".join(f"{t}. {ini}" for t, ini in faculty)
                is_dept = subject.upper() in DEPARTMENTS and not initials
                entries.append((current_room, day, slot_id[(s, e)], subject.strip(), initials, fac_label, is_dept))

    print("-- Generated by scripts/parse_timetable.py from the Room Allocation Time Table. Do not edit by hand.")
    print("begin;")
    print("insert into public.rooms (id, name, sort_order) values")
    print(",\n".join(f"  ({q(r)}, {q(r)}, {n})" for n, r in enumerate(rooms)) + "\non conflict (id) do nothing;")
    print("insert into public.slots (id, starts, ends, label) values")
    print(",\n".join(f"  ({n + 1}, {q(s)}, {q(e)}, {q(label(s, e))})" for n, (s, e) in enumerate(slots))
          + "\non conflict (id) do nothing;")
    name = f"Room Allocation Time Table{', revised ' + revised if revised else ''}"
    print(f"insert into public.timetable_versions (id, name, valid_from, valid_to) values "
          f"({version}, {q(name)}, {q(valid_from)}, {q(valid_to)});")
    print(f"select setval('public.timetable_versions_id_seq', greatest({version}, (select max(id) from public.timetable_versions)));")
    print("insert into public.timetable_entries "
          "(version_id, room_id, weekday, slot_id, subject, faculty_initials, faculty_label, is_department) values")
    rows = []
    for room, day, slot, subject, initials, fac_label, is_dept in entries:
        arr = "array[" + ",".join(q(i) for i in initials) + "]::text[]" if initials else "'{}'::text[]"
        rows.append(f"  ({version}, {q(room)}, {day}, {slot}, {q(subject)}, {arr}, {q(fac_label)}, {str(is_dept).lower()})")
    print(",\n".join(rows) + ";")
    print("commit;")
    print(f"-- {len(rooms)} rooms, {len(slots)} slots, {len(entries)} timetable entries", file=sys.stderr)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("docx")
    ap.add_argument("--version", type=int, default=1, help="timetable version id (1 for the first import)")
    ap.add_argument("--from", dest="valid_from", default=VALID_FROM, help="first day it applies, YYYY-MM-DD")
    ap.add_argument("--to", dest="valid_to", default=VALID_TO, help="last day of the semester, YYYY-MM-DD")
    a = ap.parse_args()
    main(a.docx, a.version, a.valid_from, a.valid_to)
